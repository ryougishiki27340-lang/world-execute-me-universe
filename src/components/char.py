"""The whale girl: interface portrait window + data-space forms.

INTERFACE FORM loads assets/char (allowed). DATA FORMS are generated by the
film's own visualisation system and MUST NOT open the art files (static rule:
data-space render code never references the portrait assets).
"""
from __future__ import annotations

import math

from PIL import Image, ImageDraw, ImageOps

from engine.prng import prng

ROOT = __import__("pathlib").Path(__file__).resolve().parents[2]


def portrait_window(img, cfg, t, expr, rect, title="her"):
    """The personality window (interface mode). Expression = one of the 8."""
    assets = str(ROOT / cfg["character"]["assets_dir"])
    fname = cfg["character"]["expressions"][expr]
    src = Image.open(f"{assets}/{fname}").convert("RGBA")
    x0, y0, x1, y1 = rect
    w, h = x1 - x0, y1 - y0
    scale = min(w / src.width, h / src.height)
    sw, sh = int(src.width * scale), int(src.height * scale)
    im = src.resize((sw, sh), Image.LANCZOS)
    px, py = x0 + (w - sw) // 2, y0 + (h - sh) // 2
    d = ImageDraw.Draw(img)
    d.rounded_rectangle(rect, radius=10, fill=(12, 14, 20), outline=(70, 78, 96), width=2)
    d.rectangle([x0, y0 - 18, x0 + 120, y0], fill=(12, 14, 20))
    from engine.draw import text as txt
    txt(img, (x0 + 8, y0 - 18), title, cfg["fonts"]["mono"], 15, (180, 190, 210))
    img.paste(im, (px, py), im)
    return rect


def char_crop(expr, out_h, band=(0.0, 1.0), assets_dir="assets/char"):
    """A band crop of the portrait art (interface form only; hand close-ups)."""
    src = Image.open(f"{ROOT / assets_dir}/whale-{expr}.webp").convert("RGBA")
    y0, y1 = int(src.height * band[0]), int(src.height * band[1])
    im = src.crop((0, y0, src.width, y1))
    w = int(im.width * out_h / im.height)
    return im.resize((w, out_h), Image.LANCZOS)


# ---------------------------------------------------------------- data forms
def _profile_pts(seed):
    """A parametric whale-girl side profile (stylised, original). Returns polygon."""
    rng = prng(seed, 0)
    pts = []
    # forehead -> nose -> lips -> chin -> jaw -> neck
    spine = [
        (0.00, 0.00), (0.10, -0.52), (0.28, -0.62), (0.46, -0.40),   # forehead to nose
        (0.50, -0.24), (0.44, -0.10), (0.40, 0.02), (0.42, 0.18),    # nose, lips, chin
        (0.34, 0.42), (0.18, 0.54), (0.02, 0.58), (-0.04, 0.74),     # jaw to neck
        (-0.14, 0.78), (-0.16, 0.52), (-0.22, 0.30), (-0.24, 0.04),  # neck up the back
        (-0.20, -0.28), (-0.10, -0.44),
    ]
    for x, y in spine:
        pts.append((x + rng.uniform(-0.012, 0.012), y + rng.uniform(-0.012, 0.012)))
    # whale fin on top (her motif)
    fin = [(-0.02, -0.50), (-0.10, -0.86), (0.10, -0.62), (0.16, -0.56)]
    pts[1:1] = fin
    return pts


def point_side_face(img, cfg, t, center, radius, *, align=1.0, fill=(232, 230, 223),
                    n=2600, ds=2.0):
    """Her data form: the profile as a dot matrix. align 0..1 gathers the points.
    Points are grid-sampled inside the profile polygon (dense, uniform); before
    full alignment they scatter from a cloud and land on their cells."""
    seed = cfg["character"]["silhouette_seed"]
    rng = prng(seed, 7)
    poly = _profile_pts(seed)
    d = ImageDraw.Draw(img)
    cx, cy = center
    # uniform grid over the profile bbox; keep interior cells + edge cells
    u0, u1, v0, v1 = -0.30, 0.56, -0.90, 0.84
    nx = int(round(math.sqrt(n * (u1 - u0) / (v1 - v0))))
    ny = int(round(nx * (v1 - v0) / (u1 - u0)))
    pts = []
    for gy in range(ny):
        for gx in range(nx):
            u = u0 + (u1 - u0) * (gx + 0.5) / nx
            v = v0 + (v1 - v0) * (gy + 0.5) / ny
            if not _inside(poly, (u, v)):
                continue
            jx = rng.uniform(-0.008, 0.008)
            jy = rng.uniform(-0.008, 0.008)
            pts.append((u + jx, v + jy))
    for u, v in pts:
        sx = cx + (rng.random() - 0.5) * radius * 3.4
        sy = cy + (rng.random() - 0.5) * radius * 2.6
        x = sx + (cx + u * radius - sx) * align
        y = sy + (cy + v * radius - sy) * align
        a = int(110 + 145 * align)
        d.rectangle([x - ds / 2, y - ds / 2, x + ds / 2, y + ds / 2],
                    fill=fill + (a,))
    return center


def _inside(poly, p):
    x, y = p
    inside = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def ascii_whale(img, cfg, t, center, size=14):
    """ASCII whale glyph built from a parametric silhouette (data form)."""
    from engine.draw import text as txt
    rng = prng(cfg["character"]["silhouette_seed"], 11)
    cx, cy = center
    # a small whale: body arc + tail, drawn as glyph cells
    ImageDraw.Draw(img).ellipse([cx - 80, cy - 34, cx + 80, cy + 34], fill=(52, 92, 140))
    for i in range(34):
        a = math.pi * (0.15 + 0.7 * i / 34)
        x = cx + math.cos(a) * 80
        y = cy - math.sin(a) * 34
        ch = "MW08@#"[rng.randrange(6)]
        txt(img, (x, y), ch, cfg["fonts"]["mono"], size, (120, 205, 240), anchor="mm")
    for i in range(22):
        a = math.pi * (0.22 + 0.56 * i / 22)
        x = cx + math.cos(a) * 58
        y = cy - math.sin(a) * 22
        txt(img, (x, y), rng.choice("@#%"), cfg["fonts"]["mono"], size, (170, 225, 250), anchor="mm")
    txt(img, (cx - 78, cy + 8), "~~", cfg["fonts"]["mono"], size, (120, 205, 240), anchor="mm")
